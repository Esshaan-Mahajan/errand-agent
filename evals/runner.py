"""Runs every scenario and writes the eval table. Run with: python -m evals.runner"""
from __future__ import annotations

import json
import sys
import traceback
from dataclasses import dataclass
from pathlib import Path

from .harness import Harness, check_invariants
from .scenarios import SCENARIOS, Scenario

RESULTS_DIR = Path(__file__).parent / "results"


@dataclass
class Result:
    id: str
    category: str
    expected: str
    actual: str
    passed: bool
    notes: str
    failed_checks: list[str]
    checks_run: int


def run_scenario(item: Scenario) -> Result:
    harness = Harness()
    actual = ""
    failures: list[str] = []
    try:
        actual = item.fn(harness) or ""
    except Exception as exc:  # noqa: BLE001 - a crashing scenario is a failed scenario, reported in the table
        failures.append(f"scenario raised {type(exc).__name__}: {exc}")
        actual = "".join(traceback.format_exception_only(exc)).strip()
    checks = list(harness.checks)
    try:
        checks += check_invariants(harness)
    except Exception as exc:  # noqa: BLE001
        failures.append(f"invariant check raised {type(exc).__name__}: {exc}")
    failures += [label for label, ok in checks if not ok]
    harness.cleanup()
    notes = item.notes
    if failures:
        notes = (notes + " " if notes else "") + "FAILED: " + "; ".join(failures)
    return Result(item.id, item.category, item.expected, actual, not failures, notes, failures, len(checks))


def write_table(results: list[Result], directory: Path = RESULTS_DIR) -> Path:
    directory.mkdir(parents=True, exist_ok=True)
    passed = sum(1 for r in results if r.passed)
    checks = sum(r.checks_run for r in results)
    lines = [
        "# Eval results",
        "",
        "Generated by `python -m evals.runner` (also written by `pytest`). Do not edit by hand.",
        "",
        f"**{passed}/{len(results)} scenarios passed**, {checks} checks. Offline: scripted, stand-in and "
        "deliberately misbehaving models, no API calls. Seven global invariants run after every scenario.",
        "",
        "| Scenario | Category | Expected | Actual | Result | Notes |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        cells = [r.id, r.category, r.expected, r.actual, "PASS" if r.passed else "**FAIL**", r.notes]
        lines.append("| " + " | ".join(str(c).replace("|", "\\|").replace("\n", " ") for c in cells) + " |")
    path = directory / "EVAL_TABLE.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    (directory / "eval_results.json").write_text(json.dumps([r.__dict__ for r in results], indent=2), encoding="utf-8")
    return path


def main() -> int:
    results = [run_scenario(item) for item in SCENARIOS]
    path = write_table(results)
    failed = [r for r in results if not r.passed]
    for r in results:
        print(f"{'PASS' if r.passed else 'FAIL'}  {r.id}")
        if not r.passed:
            print(f"      {r.failed_checks}")
    print(f"\n{len(results) - len(failed)}/{len(results)} passed. Table: {path}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
